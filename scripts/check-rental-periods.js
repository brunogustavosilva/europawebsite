import { formatDate } from '../src/components/admin/helpers.js';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import '../server/env.js';
import { plusDays, addMonths } from '../server/admin-domain.js';
assert.equal(process.env.ALLOW_ADMIN_FIXTURES, '1');
assert.ok(process.env.NEON_BRANCH?.startsWith('dev-'));
assert.ok(process.env.ADMIN_TEST_PASSWORD);
const base = process.env.TEST_BASE_URL || 'http://localhost:5182';
const browser = await chromium.launch();
try {
    const context = await browser.newContext();
    const http = context.request;
    assert.equal((await http.post(`${base}/api/admin/login`, { data: { username: process.env.ADMIN_USERNAME, password: process.env.ADMIN_TEST_PASSWORD } })).status(), 200);
    const dashboard = await (await http.get(`${base}/api/admin/dashboard`)).json();
    const month = addMonths(dashboard.today.slice(0,7), 1);
    const first = `${month}-15`;
    const suffix = Date.now();
    async function api(path, data, method = 'post', status = 201) {
        const response = await http[method](`${base}/api/admin${path}`, { data });
        const result = await response.json();
        assert.equal(response.status(), status, JSON.stringify(result));
        return result;
    }
    const equipmentData = { nome: `Períodos ${suffix}`, stock: 2, preco: '50', unit_cost: '100', voltage: 'bivolt', tag: 'visual' };
    const equipment = await api('/equipment', equipmentData);
    const payload = (date, quantity = 1, status = 'prevista') => ({ customer_name: `Cliente períodos ${date} ${suffix}`, phone: '(41) 9 9999-9999', address: '', delivery: false, rental_date: date, status, total: '50', deposit: '0', items: [{ equipment_id: equipment.id, quantity }] });
    const a = await api('/rentals', payload(first));
    const b = await api('/rentals', payload(plusDays(first,5)));
    const availability = await (await http.get(`${base}/api/admin/inventory?rentalDate=${plusDays(first,2)}`)).json();
    const item = availability.items.find((item) => item.id === equipment.id);
    assert.equal(item.reserved, 1);
    assert.equal(item.available, 1);
    const c = await api('/rentals', payload(plusDays(first,2)));
    await api('/rentals', payload(plusDays(first,4)), 'post', 409);
    await api(`/equipment/${equipment.id}`, { ...equipmentData, stock: 1 }, 'put', 409);
    const records = await (await http.get(`${base}/api/admin/dashboard?month=${month}`)).json();
    const savedA = records.rentals.find((rental) => rental.id === a.id);
    assert.equal(savedA.occupied_from, first);
    assert.equal(savedA.occupied_until, plusDays(first,4));
    const excluded = await (await http.get(`${base}/api/admin/inventory?rentalDate=${first}&exclude=${a.id}`)).json();
    assert.equal(excluded.items.find((item) => item.id === equipment.id).available,1);
    await api(`/rentals/${c.id}`, payload(plusDays(first,2),1,'cancelada'), 'put', 200);
    await api('/rentals', payload(plusDays(first,4)));
    await api(`/rentals/${b.id}`, payload(plusDays(first,5),1,'cancelada'), 'put', 200);
    await api(`/rentals/${a.id}`, payload(plusDays(first,1)), 'put', 200);
    const updated = await (await http.get(`${base}/api/admin/dashboard?month=${month}`)).json();
    assert.equal(updated.rentals.find((rental) => rental.id === a.id).occupied_until, plusDays(first,5));
    const secondEquipment = await api('/equipment', { ...equipmentData, nome: `Virada de mês ${suffix}`, stock: 1 });
    const nextMonth = `${addMonths(month,1)}-01`;
    const crossMonthDate = plusDays(nextMonth,-2);
    await api('/rentals', { ...payload(crossMonthDate), items: [{ equipment_id: secondEquipment.id, quantity: 1 }] });
    await api('/rentals', { ...payload(nextMonth), items: [{ equipment_id: secondEquipment.id, quantity: 1 }] }, 'post', 409);
    await api('/rentals', { ...payload(plusDays(crossMonthDate,5)), items: [{ equipment_id: secondEquipment.id, quantity: 1 }] });
    console.log('PASS períodos: dia 15 ao 19 inclusive; sobreposições bloqueadas; liberação após término; viradas de semana e mês');
    console.log('PASS estoque: pico diário evita somar reservas não simultâneas; edição, cancelamento e redução de estoque validados');
    let midweek = `${month}-01`;
    while (new Date(`${midweek}T12:00:00Z`).getUTCDay() !== 2) midweek = plusDays(midweek,1);
    const uiEquipment = await api('/equipment', { ...equipmentData, nome: `Reserva terça ${suffix}`, stock: 1 });
    const page = await context.newPage();
    await page.goto(`${base}/admin`);
    await page.getByRole('button', { name: 'Cadastrar locação' }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nome do cliente', {exact:true}).fill(`Terça-feira ${suffix}`);
    await dialog.getByLabel('Telefone', {exact:true}).fill('41999999999');
    await dialog.getByLabel('Data da locação', {exact:true}).fill(formatDate(midweek));
    await dialog.getByLabel('Equipamento 1',{exact:true}).selectOption(uiEquipment.id);
    await dialog.getByRole('button',{name:'Usar este valor',exact:true}).click();
    await dialog.getByRole('button',{name:'Salvar locação',exact:true}).click();
    await page.getByText('Locação salva com sucesso.',{exact:false}).waitFor();
    await page.getByRole('button',{name:`Terça-feira ${suffix}`,exact:true}).click();
    await dialog.getByRole('heading',{name:`Terça-feira ${suffix}`,exact:true}).waitFor();
    const expectedEnd = new Date(`${plusDays(midweek,4)}T12:00:00`).toLocaleDateString('pt-BR');
    assert.ok((await dialog.innerText()).includes(expectedEnd));
    console.log('PASS navegador: cadastro em terça-feira e período de ocupação exibido corretamente');
} finally { await browser.close(); }
