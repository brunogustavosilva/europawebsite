import { formatDate } from '../src/components/admin/helpers.js';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import '../server/env.js';
import { plusDays } from '../server/admin-domain.js';

assert.equal(process.env.ALLOW_ADMIN_FIXTURES, '1', 'Execute apenas em uma branch de teste, com ALLOW_ADMIN_FIXTURES=1.');
assert.ok(process.env.NEON_BRANCH?.startsWith('dev-'), 'Use uma branch Neon dev- para este teste.');
assert.ok(process.env.ADMIN_TEST_PASSWORD, 'Informe ADMIN_TEST_PASSWORD no ambiente.');
const base = process.env.TEST_BASE_URL || 'http://localhost:5182';
const browser = await chromium.launch();
const suffix = Date.now().toString();
try {
    const context = await browser.newContext();
    const req = context.request;
    assert.equal((await req.get(`${base}/api/admin/dashboard`)).status(), 401);
    let login = await req.post(`${base}/api/admin/login`, { data: { username: process.env.ADMIN_USERNAME, password: process.env.ADMIN_TEST_PASSWORD } });
    assert.equal(login.status(), 200);
    async function api(path, body, method = 'post', expected = 201) {
        const response = await req[method](`${base}/api/admin${path}`, { data: body });
        const result = await response.json();
        assert.equal(response.status(), expected, JSON.stringify(result));
        return result;
    }
    let initial = await (await req.get(`${base}/api/admin/dashboard`)).json();
    const today = initial.today;
    assert.equal(initial.months.length, 7);
    assert.equal(initial.months.filter((item) => item.closed).length, 2);
    let future = plusDays(today, 1);
    while (new Date(`${future}T12:00:00Z`).getUTCDay() !== 5) future = plusDays(future, 1);
    let past = today;
    while (new Date(`${past}T12:00:00Z`).getUTCDay() !== 5) past = plusDays(past, -1);
    if (past.slice(0,7) !== today.slice(0,7)) past = today; // Em virada de mês, só conclui se a data for elegível.
    const equipmentBody = { nome: `Teste dashboard ${suffix}`, stock: 2, preco: '100.50', unit_cost: '9999', voltage: '220', tag: 'som' };
    const equipment = await api('/equipment', equipmentBody);
    function rental(date, name, extra = {}) {
        return { customer_name: `${name} ${suffix}`, phone: '41999999999', address: 'Rua de teste, 100', rental_date: date, total: '500', deposit: '100', delivery: true, status: 'prevista', notes: 'Fixture da branch de teste', items: [{ equipment_id: equipment.id, quantity: 1 }], ...extra };
    }
    const plannedBody = rental(future, 'Cliente previsto');
    const planned = await api('/rentals', plannedBody);
    const concurrent = await Promise.all([req.post(`${base}/api/admin/rentals`, { data: rental(future, 'Concorrente A') }), req.post(`${base}/api/admin/rentals`, { data: rental(future, 'Concorrente B') })]);
    assert.deepEqual(concurrent.map((response) => response.status()).sort(), [201,409]);
    const winning = concurrent.find((response) => response.status() === 201);
    const winningId = (await winning.json()).id;
    const monday = plusDays(future, 3);
    await api('/rentals', rental(monday, 'Segunda ocupada'), 'post', 409);
    await api(`/rentals/${winningId}`, rental(future, 'Cancelada', { status: 'cancelada' }), 'put', 200);
    await api('/rentals', rental(monday, 'Cliente segunda'));
    let inventory = await (await req.get(`${base}/api/admin/inventory?rentalDate=${monday}`)).json();
    let stock = inventory.items.find((item) => item.id === equipment.id);
    assert.equal(inventory.occupiedFrom, monday);
    assert.equal(stock.available, 0);
    await api(`/equipment/${equipment.id}`, { ...equipmentBody, stock: 1 }, 'put', 409);
    console.log('PASS estoque: períodos sobrepostos compartilham estoque; concorrência e redução de estoque bloqueadas; cancelamento libera unidades');
    await api(`/equipment/${equipment.id}`, { ...equipmentBody, preco: '130' }, 'put', 200);
    await api(`/rentals/${planned.id}`, plannedBody, 'put', 200);
    let monthly = await (await req.get(`${base}/api/admin/dashboard?month=${future.slice(0,7)}`)).json();
    assert.equal(monthly.rentals.find((item) => item.id === planned.id).items[0].unit_price, 100.5);
    await api('/rentals', rental(`${initial.months[0].month}-02`, 'Mês fechado'), 'post', 409);
    await api('/rentals', rental(future, 'Futura concluída', { status: 'concluida' }), 'post', 400);
    console.log('PASS regras: mês encerrado bloqueia escrita; futura não pode ser concluída; preço dos itens preservado');
    if ([0,1,5,6].includes(new Date(`${past}T12:00:00Z`).getUTCDay())) {
        const before = await (await req.get(`${base}/api/admin/dashboard?month=${past.slice(0,7)}`)).json();
        const beforeSummary = before.months.find((item) => item.month === past.slice(0,7));
        await api('/rentals', rental(past, 'Cliente concluído', { total: '450', deposit: '50', status: 'concluida' }));
        const after = await (await req.get(`${base}/api/admin/dashboard?month=${past.slice(0,7)}`)).json();
        const summary = after.months.find((item) => item.month === past.slice(0,7));
        assert.equal(summary.completedValue, beforeSummary.completedValue + 450);
        assert.equal(summary.completedCount, beforeSummary.completedCount + 1);
        assert.equal(summary.plannedValue, beforeSummary.plannedValue);
        console.log('PASS dashboard: conclusão soma R$ 450 e uma locação; sinal de R$ 50 não é somado');
    }
    const page = await context.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(`${base}/admin`);
    await page.getByRole('heading', { name: 'Visão geral', exact: true }).waitFor();
    await page.getByText('Locações do mês', { exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/eurolight-dashboard-desktop.png', fullPage: true });
    const closedMonthButton = page.locator('.month-switcher button').first();
    await closedMonthButton.click();
    await page.getByText('Mês encerrado', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Equipamentos', exact: true }).click();
    await page.getByRole('heading', { name: 'Estoque de equipamentos' }).waitFor();
    await page.getByLabel('Filtrar por tag').selectOption('som');
    await page.getByLabel('Ordenar equipamentos').selectOption('price-desc');
    await page.screenshot({ path: '/tmp/eurolight-inventory-desktop.png', fullPage: true });
    await page.getByRole('button', { name: 'Cadastrar equipamento' }).click();
    await page.getByLabel('Nome do equipamento', { exact: true }).fill(`Cadastro pela tela ${suffix}`);
    await page.getByLabel('Link da imagem', { exact: false }).fill('https://example.com/equipamento-teste.jpg');
    await page.getByLabel('Quantidade em estoque', { exact: true }).fill('3');
    await page.getByLabel('Locação por fim de semana (R$)', { exact: true }).fill('25');
    await page.getByLabel('Preço de compra por unidade (R$)', { exact: true }).fill('100');
    await page.getByRole('button', { name: 'Salvar equipamento', exact: true }).click();
    await page.getByText('Equipamento salvo com sucesso.', { exact: false }).waitFor();
    await page.getByRole('button', { name: 'Geral', exact: true }).click();
    await page.getByRole('button', { name: 'Cadastrar locação' }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Nome do cliente', { exact: true }).fill(`Cliente pela tela ${suffix}`);
    await dialog.getByLabel('Telefone', { exact: true }).fill('41999999999');
    await dialog.getByLabel('Data da locação', { exact: true }).fill(formatDate(future));
    await dialog.getByLabel('Equipamento 1', { exact: true }).selectOption({ label: `Cadastro pela tela ${suffix} · 3 livre(s) · R$ 25,00` });
    await dialog.getByRole('button', { name: 'Usar este valor', exact: true }).click();
    await dialog.getByRole('button', { name: 'Salvar locação', exact: true }).click();
    await page.getByText('Locação salva com sucesso.', { exact: false }).waitFor();
    await page.getByRole('button', { name: `Cliente pela tela ${suffix}`, exact: true }).click();
    await dialog.getByRole('heading', { name: `Cliente pela tela ${suffix}`, exact: true }).waitFor();
    assert.match(await dialog.innerText(), /Retirada pelo cliente/);
    await dialog.evaluate(async (element) => { await Promise.all(element.getAnimations().map((animation) => animation.finished)); });
    await page.screenshot({ path: '/tmp/eurolight-rental-detail.png' });
    await page.getByRole('button', { name: 'Fechar Detalhes da locação', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '/tmp/eurolight-dashboard-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('PASS navegador: meses fechados, filtros, cadastro de equipamento, cadastro de locação, detalhes e layout móvel');
    await context.close();
} finally { await browser.close(); }
